#!/usr/bin/env python3
"""Tighten runtime grants after migrations, without exposing root or application credentials."""
import subprocess


def run(sql):
    return subprocess.run(['docker', 'exec', '-i', 'mysql', 'sh', '-c',
                           'export MYSQL_PWD="$MYSQL_ROOT_PASSWORD"; exec mysql -uroot -N'],
                          input=sql, text=True, capture_output=True, check=True).stdout


def main():
    version = run("SELECT version FROM huimeng.flyway_schema_history WHERE success=1 ORDER BY installed_rank DESC LIMIT 1;").strip()
    if version != '3':
        raise SystemExit('Expected migrated schema v3')
    account = "'huimeng_app'@'172.29.46.%'"
    # Revoke the temporary schema DML grant generated by the initial provisioner.
    current = run("SELECT PRIVILEGE_TYPE FROM information_schema.SCHEMA_PRIVILEGES WHERE GRANTEE=CONCAT(CHAR(39),'huimeng_app',CHAR(39),'@',CHAR(39),'172.29.46.%',CHAR(39)) AND TABLE_SCHEMA='huimeng';")
    statements = []
    for privilege in ['INSERT', 'UPDATE', 'DELETE']:
        if privilege in current.splitlines():
            statements.append(f'REVOKE {privilege} ON huimeng.* FROM {account};')
    statements.append(f'GRANT SELECT ON huimeng.* TO {account};')
    for table in ['users', 'projects', 'project_members', 'provider_secrets', 'approved_models',
                  'external_clients', 'external_grants', 'generation_runs', 'user_preferences']:
        statements.append(f'GRANT INSERT,UPDATE,DELETE ON huimeng.{table} TO {account};')
    statements.append(f'GRANT UPDATE ON huimeng.bootstrap_lock TO {account};')
    statements.append(f'GRANT INSERT,DELETE ON huimeng.audit_events TO {account};')
    run('\n'.join(statements))
    print('Runtime grants tightened: business DML only; schema history read-only; audit cannot be updated')


if __name__ == '__main__':
    try:
        main()
    except subprocess.CalledProcessError:
        raise SystemExit('Database grant finalization failed; no secret output')
